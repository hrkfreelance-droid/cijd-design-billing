export const dictionaries: Record<Locale, Record<MessageKey, string>> = { en, ja, kh };

export function translate(
  locale: Locale,
  key: MessageKey,
  vars?: Record<string, string | number>,
): string {
  // "3 items" but "1 item": a key may ship a `<key>One` singular variant.
  let resolved = key;
  if (vars?.count === 1) {
    const singular = `${key}One` as MessageKey;
    if (singular in dictionaries[locale]) resolved = singular;
  }
  const template = dictionaries[locale][resolved] ?? key;
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in vars ? String(vars[name]) : match,
  );
}
