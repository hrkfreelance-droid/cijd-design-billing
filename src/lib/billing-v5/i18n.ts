const dictionaries = { en, ja, kh } as const;

export function v5Translate(locale: "ja" | "en" | "kh", key: V5Key, vars?: Record<string, string | number>): string {
  let text: string = dictionaries[locale]?.[key] ?? en[key];
  if (vars) for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
  return text;
}

export function useV5T() {
  const { locale } = useI18n();
  return useCallback(
    (key: V5Key, vars?: Record<string, string | number>) => v5Translate(locale, key, vars),
    [locale],
  );
}
