function resolvedInvoiceKind(raw: string | undefined, fallback: TaxInvoiceKind = "FULL"): TaxInvoiceKind {
  const value = raw ?? fallback;
  if (value === "FULL" || value === "DEPOSIT_FIXED" || value === "DEPOSIT_PERCENT" || value === "FINAL") return value;
  throw new RuleError("INVALID_INVOICE_KIND", "Choose FULL, DEPOSIT fixed, DEPOSIT percent, or FINAL.", 400);
}

function isDepositKind(kind: TaxInvoiceKind): kind is "DEPOSIT_FIXED" | "DEPOSIT_PERCENT" {
  return kind === "DEPOSIT_FIXED" || kind === "DEPOSIT_PERCENT";
}

function activeContractInvoices(db: Database, contractId: string, excludeInvoiceId: string | null = null): TaxInvoiceRecord[] {
  return (db.taxInvoices ?? []).filter(
    (invoice) => invoice.contractId === contractId && invoice.status === "ISSUED" && invoice.id !== excludeInvoiceId,
  );
}

function activeDeposits(db: Database, contractId: string, excludeInvoiceId: string | null = null): TaxInvoiceRecord[] {
  return activeContractInvoices(db, contractId, excludeInvoiceId)
    .filter((invoice) => isDepositKind(invoice.invoiceKind ?? "FULL"))
    .sort((a, b) => a.issuedAt.localeCompare(b.issuedAt) || a.invoiceNumber.localeCompare(b.invoiceNumber));
}

function referencesFrom(invoices: readonly TaxInvoiceRecord[]): TaxInvoiceDepositReference[] {
  return invoices.map((invoice) => ({
    invoiceId: invoice.id,
    invoiceNumber: invoice.invoiceNumber,
    subtotalUsd: invoice.subtotalUsd,
    vatUsd: invoice.vatUsd,
    totalUsd: invoice.totalUsd,
    allocations: invoice.lines
      .filter((line) => line.billingItemId)
      .map((line) => ({ billingItemId: line.billingItemId!, description: line.description.replace(/^Advance portion: /, ""), amount: line.amount })),
  }));
}

function contractSnapshotFromDatabase(db: Database, contractId: string, customerId: string): TaxInvoiceContractSnapshot {
  const contractInvoices = (db.taxInvoices ?? []).filter((invoice) => invoice.contractId === contractId);
  if (!contractInvoices.length) throw new RuleError("NOT_FOUND", "Deposit contract was not found.", 404);
  if (contractInvoices.some((invoice) => invoice.clientId !== customerId)) {
    throw new RuleError("DIFFERENT_CUSTOMER", "This deposit contract belongs to a different customer.", 400);
  }
  const snapshot = contractInvoices.find((invoice) => invoice.contractSnapshot)?.contractSnapshot;
  if (!snapshot || snapshot.id !== contractId || snapshot.clientId !== customerId) {
    throw new RuleError("INVALID_CONTRACT", "The deposit contract snapshot is missing or inconsistent.", 409);
  }
  const subtotalCents = snapshot.lines.reduce((sum, line) => sum + toCents(line.amount), 0);
  if (
    subtotalCents !== toCents(snapshot.subtotalUsd) ||
    toCents(snapshot.totalUsd) !== toCents(snapshot.subtotalUsd) + toCents(snapshot.vatUsd)
  ) {
    throw new RuleError("INVALID_CONTRACT", "The deposit contract amounts do not reconcile.", 409);
  }
  return snapshot;
}

interface ContractRemainder {
  lines: TaxInvoiceContractLine[];
  centsByBillingItem: Map<string, number>;
  contractInvoices: TaxInvoiceRecord[];
}

/** Recompute remaining contract cents only from the transaction's current allocations. */
function contractRemainder(
  db: Database,
  contract: TaxInvoiceContractSnapshot,
  excludeInvoiceId: string | null,
): ContractRemainder {
  const contractInvoices = activeContractInvoices(db, contract.id, excludeInvoiceId);
  const invoiceIds = new Set(contractInvoices.map((invoice) => invoice.id));
  const centsByBillingItem = new Map<string, number>();
  for (const line of contract.lines) {
    const item = db.billingItems.find((entry) => entry.id === line.billingItemId && !entry.deletedAt);
    const project = item && db.projects.find((entry) => entry.id === item.projectId && !entry.deletedAt);
    if (!item || !project || project.clientId !== contract.clientId) {
      throw new RuleError("INVALID_CONTRACT", "A linked billing line is no longer available to this customer.", 409);
    }
    const allocations = (db.billingAllocations ?? []).filter(
      (allocation) => allocation.billingItemId === line.billingItemId && !allocation.voidedAt && allocation.invoiceId !== excludeInvoiceId,
    );
    if (allocations.some((allocation) => !invoiceIds.has(allocation.invoiceId))) {
      throw new RuleError("INVOICE_KIND_CONFLICT", `"${item.description}" has an allocation outside this deposit contract.`, 409);
    }
    const allocatedCents = allocations.reduce((sum, allocation) => sum + toCents(allocation.amount), 0);
    const remainingCents = toCents(line.amount) - allocatedCents;
    if (remainingCents < 0) throw new RuleError("INVALID_CONTRACT", `"${item.description}" is allocated above the contract amount.`, 409);
    centsByBillingItem.set(line.billingItemId, remainingCents);
  }
  return { lines: contract.lines, centsByBillingItem, contractInvoices };
}

function requiredBillingIds(input: InvoiceInput): string[] {
  if (!Array.isArray(input.items) || input.items.length === 0) throw new RuleError("NO_ITEMS", "Choose at least one linked billing line.", 400);
  if (input.items.length > MAX_INVOICE_ITEMS) throw new RuleError("TOO_MANY_LINES", `An invoice holds at most ${MAX_INVOICE_ITEMS} lines.`, 400);
  const ids: string[] = [];
  for (const item of input.items) {
    if (!item.billingItemId || item.productId) {
      throw new RuleError("DEPOSIT_REQUIRES_BILLING_LINES", "Deposit and final invoices can only contain linked billing lines; free and product lines are not supported.", 400);
    }
    if (ids.includes(item.billingItemId)) throw new RuleError("DUPLICATE_BILLING_LINE", "Choose each linked billing line once.", 400);
    ids.push(item.billingItemId);
  }
  return ids;
}

function validateSpecialOptions(input: InvoiceInput) {
  if (input.discount) throw new RuleError("DEPOSIT_RESTRICTION", "Discounts are not supported on deposit or final invoices.", 400);
  const paymentDeposit = input.depositUsd ?? 0;
  if (!Number.isFinite(paymentDeposit) || paymentDeposit !== 0) {
    throw new RuleError("DEPOSIT_RESTRICTION", "Deposit received is a payment field and must be zero on deposit or final invoices.", 400);
  }
}

function specialTotals(subtotalCents: number, vatCents: number, vatPercent: number, exchangeRate: number): InvoiceTotals {
  const totalCents = subtotalCents + vatCents;
  const subtotal = fromCents(subtotalCents);
  const total = fromCents(totalCents);
  return {
    subtotalUsd: subtotal,
    discountUsd: 0,
    taxableUsd: subtotal,
    vatPercent,
    vatUsd: fromCents(vatCents),
    totalUsd: total,
    totalKhr: totalKhrForCents(totalCents, exchangeRate),
    depositUsd: 0,
    balanceDueUsd: total,
    discountPolicy: null,
  };
}

function invoiceLinesForCents(
  db: Database,
  contract: TaxInvoiceContractSnapshot,
  centsByBillingItem: ReadonlyMap<string, number>,
  label: "Advance portion" | "Final remainder",
): Prepared {
  const lines: TaxInvoiceLine[] = [];
  const perBilling = new Map<string, number>();
  const projectIds: string[] = [];
  for (const contractLine of contract.lines) {
    const cents = centsByBillingItem.get(contractLine.billingItemId) ?? 0;
    if (cents <= 0) continue;
    const item = db.billingItems.find((entry) => entry.id === contractLine.billingItemId)!;
    if (!projectIds.includes(item.projectId)) projectIds.push(item.projectId);
    const amount = fromCents(cents);
    lines.push({
      billingItemId: contractLine.billingItemId,
      projectName: contractLine.projectName,
      description: `${label}: ${contractLine.description}`,
      quantity: 1,
      unit: label === "Advance portion" ? "advance" : "remainder",
      unitPrice: amount,
      amount,
    });
    perBilling.set(contractLine.billingItemId, amount);
  }
  if (!lines.length) throw new RuleError("NO_REMAINING_CONTRACT", "There is no remaining contract amount to invoice.", 409);
  return { lines, perBilling, projectIds };
}

function assertNoExistingAllocation(db: Database, billingItemId: string) {
  const contractInvoice = activeContractInvoiceForBillingItem(db, billingItemId);
  if (contractInvoice) {
    throw new RuleError("INVOICE_KIND_CONFLICT", `"${db.billingItems.find((item) => item.id === billingItemId)?.description ?? "Billing line"}" is already part of deposit contract ${contractInvoice.invoiceNumber}. Continue with that contract.`, 409);
  }
  const allocation = (db.billingAllocations ?? []).find((entry) => entry.billingItemId === billingItemId && !entry.voidedAt);
  if (!allocation) return;
  const invoice = db.taxInvoices!.find((entry) => entry.id === allocation.invoiceId);
  if (invoice && invoice.status === "ISSUED") {
    throw new RuleError("INVOICE_KIND_CONFLICT", `"${db.billingItems.find((item) => item.id === billingItemId)?.description ?? "Billing line"}" already belongs to invoice ${invoice.invoiceNumber}. Use its deposit contract or finish the existing invoice first.`, 409);
  }
  throw new RuleError("INVOICE_KIND_CONFLICT", "This billing line already has an active allocation that cannot be used to start a deposit contract.", 409);
}

function activeContractInvoiceForBillingItem(db: Database, billingItemId: string, excludeInvoiceId: string | null = null) {
  return db.taxInvoices!.find((invoice) =>
    invoice.status === "ISSUED" && invoice.id !== excludeInvoiceId && (invoice.invoiceKind ?? "FULL") !== "FULL" &&
    invoice.contractSnapshot?.lines.some((line) => line.billingItemId === billingItemId),
  );
}

function createContractSnapshot(
  db: Database,
  customerId: string,
  ids: readonly string[],
  vatApplicable: boolean,
  exchangeRate: number,
): TaxInvoiceContractSnapshot {
  const contractId = newId();
  const lines: TaxInvoiceContractLine[] = [];
  for (const id of ids) {
    const item = db.billingItems.find((entry) => entry.id === id && !entry.deletedAt);
    const project = item && db.projects.find((entry) => entry.id === item.projectId && !entry.deletedAt);
    if (!item || !project) throw new RuleError("NOT_FOUND", "A linked billing line or project was not found.", 404);
    if (project.clientId !== customerId) throw new RuleError("DIFFERENT_CUSTOMER", "An invoice can only bill one customer's work.", 400);
    const state = billingState(db as never, item);
    if (state.legacyBilled) throw new RuleError("ALREADY_BILLED", `"${item.description}" was already billed.`);
    if (!state.eligible) throw new RuleError("NOT_READY", `"${item.description}" is not ready to bill yet.`, 409);
    assertNoExistingAllocation(db, item.id);
    const amountCents = toCents(state.remainingUsd);
    if (amountCents <= 0) throw new RuleError("NO_REMAINING_CONTRACT", `"${item.description}" has no remaining amount to invoice.`, 409);
    const amount = fromCents(amountCents);
    const quantity = item.quantity > 0 ? item.quantity : 1;
    lines.push({
      billingItemId: item.id,
      description: item.description.trim(),
      projectName: project.name.trim() || undefined,
      quantity,
      unitPrice: invoiceUnitPrice({ quantity, unitPrice: item.unitPrice, amount: item.amount ?? amount }),
      amount,
    });
  }
  const subtotalCents = lines.reduce((sum, line) => sum + toCents(line.amount), 0);
  const totals = taxTotals({ lines, vatApplicable, exchangeRate });
  return {
    id: contractId,
    clientId: customerId,
    lines,
    subtotalUsd: fromCents(subtotalCents),
    vatApplicable,
    vatPercent: totals.vatPercent,
    vatUsd: totals.vatUsd,
    totalUsd: totals.totalUsd,
  };
}

function currentContractContent(
  db: Database,
  input: InvoiceInput,
  kind: TaxInvoiceKind,
  exchangeRate: number,
  excludeInvoiceId: string | null,
  previous?: TaxInvoiceRecord,
): PreparedInvoice {
  validateSpecialOptions(input);
  const contractId = input.contractId || previous?.contractId;
  let contract: TaxInvoiceContractSnapshot;
  let remainder: ContractRemainder;
  if (contractId) {
    contract = contractSnapshotFromDatabase(db, contractId, input.customerId);
    if (!activeDeposits(db, contractId).length) {
      throw new RuleError("CONTRACT_NOT_OPEN", "This deposit contract has no active deposit invoice and cannot accept more invoices.", 409);
    }
    remainder = contractRemainder(db, contract, excludeInvoiceId);
    if ((input.vatApplicable !== false) !== contract.vatApplicable) {
      throw new RuleError("CONTRACT_VAT_IMMUTABLE", "VAT treatment is fixed by the first deposit invoice in this contract.", 409);
    }
    if (kind === "FINAL" && remainder.contractInvoices.some((invoice) => invoice.invoiceKind === "FINAL")) {
      throw new RuleError("FINAL_ALREADY_ISSUED", "This deposit contract already has an issued final invoice.", 409);
    }
    if (isDepositKind(kind) && remainder.contractInvoices.some((invoice) => invoice.invoiceKind === "FINAL")) {
      throw new RuleError("CONTRACT_FINAL_ISSUED", "No further deposit invoice can be issued after the final invoice.", 409);
    }
  } else {
    if (kind === "FINAL") throw new RuleError("CONTRACT_REQUIRED", "Choose the deposit contract this final invoice completes.", 400);
    const ids = requiredBillingIds(input);
    contract = createContractSnapshot(db, input.customerId, ids, input.vatApplicable !== false, exchangeRate);
    remainder = { lines: contract.lines, centsByBillingItem: new Map(contract.lines.map((line) => [line.billingItemId, toCents(line.amount)])), contractInvoices: [] };
  }

  const remainingIds = contract.lines
    .filter((line) => (remainder.centsByBillingItem.get(line.billingItemId) ?? 0) > 0)
    .map((line) => line.billingItemId);
  const requestedIds = requiredBillingIds(input);
  if (requestedIds.length !== remainingIds.length || requestedIds.some((id) => !remainingIds.includes(id))) {
    throw new RuleError("CONTRACT_LINES_MISMATCH", "Select every remaining linked billing line in the chosen deposit contract, and no others.", 409);
  }

  const previousDeposits = activeDeposits(db, contract.id, excludeInvoiceId);
  const previousReferences = referencesFrom(previousDeposits);
  const previouslyAllocatedBaseCents = previousDeposits.reduce((sum, invoice) => sum + toCents(invoice.subtotalUsd), 0);
  const previouslyAllocatedVatCents = previousDeposits.reduce((sum, invoice) => sum + toCents(invoice.vatUsd), 0);
  const remainingBaseCents = [...remainder.centsByBillingItem.values()].reduce((sum, cents) => sum + cents, 0);
  const contractBaseCents = toCents(contract.subtotalUsd);
  const contractVatCents = toCents(contract.vatUsd);
  if (previouslyAllocatedBaseCents > contractBaseCents || previouslyAllocatedVatCents > contractVatCents) {
    throw new RuleError("INVALID_CONTRACT", "Earlier deposit invoices exceed the frozen contract totals.", 409);
  }

  if (kind === "FINAL") {
    if (input.depositValue !== undefined) throw new RuleError("INVALID", "A final invoice does not take a deposit amount.", 400);
    const prepared = invoiceLinesForCents(db, contract, remainder.centsByBillingItem, "Final remainder");
    const subtotalCents = [...remainder.centsByBillingItem.values()].reduce((sum, cents) => sum + cents, 0);
    const vatCents = contractVatCents - previouslyAllocatedVatCents;
    return {
      ...prepared,
      invoiceKind: kind,
      vatApplicable: contract.vatApplicable,
      totals: specialTotals(subtotalCents, vatCents, contract.vatPercent, exchangeRate),
      contractId: contract.id,
      contractSnapshot: contract,
      depositReferences: previousReferences,
    };
  }

  const value = Number(input.depositValue);
  if (!Number.isFinite(value) || value <= 0) throw new RuleError("INVALID_DEPOSIT_VALUE", "Enter a deposit amount greater than zero before VAT.", 400);
  if (kind === "DEPOSIT_PERCENT" && value >= 100) throw new RuleError("INVALID_DEPOSIT_VALUE", "Deposit percent must be greater than 0% and less than 100%.", 400);
  if (kind === "DEPOSIT_FIXED" && value !== fromCents(toCents(value))) {
    throw new RuleError("INVALID_DEPOSIT_VALUE", "Enter a fixed pre-VAT deposit to the nearest cent.", 400);
  }
  const targetCents = kind === "DEPOSIT_FIXED" ? toCents(value) : percentageOfCents(remainingBaseCents, value);
  if (targetCents <= 0 || targetCents >= remainingBaseCents) {
    throw new RuleError("INVALID_DEPOSIT_VALUE", "The pre-VAT deposit must be more than $0.00 and less than the remaining contract amount.", 400);
  }
  const allocationCents = allocateCentsProportionally(
    targetCents,
    contract.lines.map((line) => ({ id: line.billingItemId, cents: remainder.centsByBillingItem.get(line.billingItemId) ?? 0 })),
  );
  const prepared = invoiceLinesForCents(db, contract, allocationCents, "Advance portion");
  const vatCents = cumulativeVatSliceCents(
    contractVatCents,
    contractBaseCents,
    previouslyAllocatedBaseCents,
    targetCents,
    previouslyAllocatedVatCents,
  );
  return {
    ...prepared,
    invoiceKind: kind,
    vatApplicable: contract.vatApplicable,
    totals: specialTotals(targetCents, vatCents, contract.vatPercent, exchangeRate),
    contractId: contract.id,
    contractSnapshot: contract,
    depositValue: kind === "DEPOSIT_FIXED" ? fromCents(toCents(value)) : value,
    depositReferences: previousReferences,
  };
}

function prepareInvoice(
  db: Database,
  input: InvoiceInput,
  exchangeRate: number,
  excludeInvoiceId: string | null,
  previous?: TaxInvoiceRecord,
): PreparedInvoice {
  const kind = resolvedInvoiceKind(input.invoiceKind, previous?.invoiceKind ?? "FULL");
  if (previous && kind !== (previous.invoiceKind ?? "FULL")) {
    throw new RuleError("INVOICE_KIND_IMMUTABLE", "An invoice cannot change between FULL, DEPOSIT, and FINAL.", 409);
  }
  if (previous?.contractId && input.contractId && input.contractId !== previous.contractId) {
    throw new RuleError("CONTRACT_IMMUTABLE", "An invoice cannot move to a different deposit contract.", 409);
  }
  if (kind !== "FULL") return currentContractContent(db, input, kind, exchangeRate, excludeInvoiceId, previous);
  if (input.contractId || input.depositValue !== undefined) {
    throw new RuleError("INVALID", "Deposit contract fields are only valid on deposit or final invoices.", 400);
  }
  const prepared = prepareItems(db, input, excludeInvoiceId);
  checkDiscountAndDeposit(input);
  return {
    ...prepared,
    invoiceKind: "FULL",
    vatApplicable: input.vatApplicable !== false,
    totals: totalsFor(input, prepared.lines, exchangeRate),
  };
}

function requestFingerprint(input: InvoiceInput, kind: TaxInvoiceKind): string {
  const value = JSON.stringify({
    customerId: input.customerId,
    invoiceDate: input.invoiceDate,
    customer: input.customer,
    items: input.items,
    discount: input.discount ?? null,
    vatApplicable: input.vatApplicable !== false,
    exchangeRate: input.exchangeRate ?? null,
    depositUsd: input.depositUsd ?? 0,
    invoiceKind: kind,
    depositValue: input.depositValue ?? null,
    contractId: input.contractId ?? null,
    note: input.note ?? null,
    invoiceNumber: input.invoiceNumber ?? null,
  });
  let hash = BigInt("14695981039346656037");
  const prime = BigInt("1099511628211");
  const mask = BigInt("18446744073709551615");
  for (let index = 0; index < value.length; index += 1) {
    hash = ((hash ^ BigInt(value.charCodeAt(index))) * prime) & mask;
  }
  return hash.toString(16).padStart(16, "0");
}

function assertDepositEditable(db: Database, invoice: TaxInvoiceRecord) {
  const contractId = invoice.contractId;
  if (!contractId || !isDepositKind(invoice.invoiceKind ?? "FULL")) return;
  if (activeContractInvoices(db, contractId).some((entry) => entry.invoiceKind === "FINAL")) {
    throw new RuleError("DEPOSIT_LOCKED", `Deposit invoice ${invoice.invoiceNumber} is locked because its FINAL invoice has been issued.`, 409);
  }
  const siblings = activeDeposits(db, contractId).filter((entry) => entry.id !== invoice.id);
  const later = siblings.some((entry) => entry.issuedAt.localeCompare(invoice.issuedAt) > 0 || (entry.issuedAt === invoice.issuedAt && entry.invoiceNumber.localeCompare(invoice.invoiceNumber) > 0));
  if (later) throw new RuleError("DEPOSIT_SEQUENCE_LOCKED", "Only the most recent deposit invoice in a contract can be edited or cancelled.", 409);
}

export function issueInvoice(db: Database, input: InvoiceInput): TaxInvoiceRecord {
  ensureCollections(db);
  const requestedKind = resolvedInvoiceKind(input.invoiceKind);
  const requestKey = input.requestKey?.trim() || "";
  if (requestKey && requestKey.length > 160) throw new RuleError("INVALID", "The invoice request key is too long.", 400);
  const fingerprint = requestKey ? requestFingerprint(input, requestedKind) : undefined;
  if (requestKey) {
    const existing = db.taxInvoices!.find((invoice) => invoice.requestKey === requestKey);
    if (existing) {
      if (existing.requestFingerprint !== fingerprint) {
        throw new RuleError("IDEMPOTENCY_CONFLICT", "This invoice request key was already used with different invoice details.", 409);
      }
      return existing;
    }
  }
  const client = db.clients.find((entry) => entry.id === input.customerId);
  if (!client) throw new RuleError("NOT_FOUND", "Choose a customer.", 404);
  if (!client.active) throw new RuleError("CUSTOMER_INACTIVE", `${client.name} is inactive. Make the customer active first.`, 409);
  if (!isIsoDate(input.invoiceDate)) throw new RuleError("INVALID", "Enter a valid invoice date.", 400);
  const customer = customerSnapshot(input.customer);
  if (!customer.companyNameEn && !customer.companyNameKm) throw new RuleError("INVALID", "Enter the customer's legal name.", 400);
  const rate = resolveRate(db, input.invoiceDate, input.exchangeRate);
  const prepared = prepareInvoice(db, input, rate.rate, null);
  const { lines, perBilling, projectIds } = prepared;
  const totals = prepared.totals;
  if (input.depositUsd && toCents(input.depositUsd) > toCents(totals.totalUsd)) {
    throw new RuleError("INVALID", "The deposit is more than the invoice total.", 400);
  }

  // Manual numbering is allowed BEFORE issue. The immutable archive and revision
  // trail retain the exact issued number; issued documents cannot be renumbered.
  // Automatic numbering includes cancelled invoices and the highest existing
  // CIJD or CIJDTI suffix for the year. Issued records themselves remain immutable.
  const year = Number(input.invoiceDate.slice(0, 4));
  const testCustomer = isTestCustomer(client.name);
  const requestedNumber = input.invoiceNumber?.trim() ?? "";
  if (requestedNumber && (testCustomer || !new RegExp(`^CIJDTI${year}\\d{3,}$`).test(requestedNumber))) {
    throw new RuleError("INVALID_INVOICE_NUMBER", `Use CIJDTI${year} followed by at least three digits, or leave blank for automatic numbering.`, 400);
  }
  const invoiceNumber = requestedNumber || nextInvoiceNumber(db, year, testCustomer);
  const exists = db.taxInvoices!.some((invoice) => invoice.invoiceNumber.toUpperCase() === invoiceNumber.toUpperCase()) ||
    db.invoices.some((invoice) => invoice.invoiceNumber?.toUpperCase() === invoiceNumber.toUpperCase());
  if (exists) throw new RuleError("DUPLICATE_INVOICE_NUMBER", `Invoice ${invoiceNumber} already exists.`, 409);
  const at = now();
  const id = newId();

  let ledgerInvoiceId = "";
  if (perBilling.size) {
    const ledger: Invoice = {
      id: newId(), clientId: client.id, invoiceNumber, invoiceDate: input.invoiceDate,
      amount: money([...perBilling.values()].reduce((sum, value) => sum + value, 0)),
      exchangeRate: rate.rate, exchangeRateSource: rate.source, exchangeRateEffectiveDate: rate.effectiveDate, exchangeRateFetchedAt: null,
      status: "ISSUED", paymentDate: null, paymentSlip: null, receiptStatus: "PENDING",
      createdAt: at, createdBy: input.actor, updatedAt: at, updatedBy: input.actor,
    };
    db.invoices.push(ledger);
    ledgerInvoiceId = ledger.id;
  }
  const projects = projectIds.map((pid) => db.projects.find((entry) => entry.id === pid)!);
  const record: TaxInvoiceRecord = {
    id,
    projectId: projectIds[0] ?? "",
    projectIds,
    clientId: client.id,
    ledgerInvoiceId,
    invoiceNumber,
    invoiceDate: input.invoiceDate,
    status: "ISSUED",
    customer,
    project: { name: projects.map((p) => p.name).join(" · "), note: projects.map((p) => p.note ?? "").filter(Boolean).join("\n") },
    lines,
    vatApplicable: input.vatApplicable !== false,
    vatPercent: totals.vatPercent,
    subtotalUsd: totals.subtotalUsd,
    discount: totals.discountUsd > 0 ? input.discount ?? null : null,
    discountUsd: totals.discountUsd,
    discountPolicy: totals.discountPolicy,
    taxableUsd: totals.taxableUsd,
    vatUsd: totals.vatUsd,
    totalUsd: totals.totalUsd,
    exchangeRate: rate.rate,
    exchangeRateSource: rate.source,
    exchangeRateEffectiveDate: rate.effectiveDate,
    exchangeRateBasis: rate.basis,
    exchangeRateForDate: rate.forDate,
    totalKhr: totals.totalKhr,
    depositUsd: totals.depositUsd,
    invoiceKind: prepared.invoiceKind,
    ...(prepared.contractId ? { contractId: prepared.contractId } : {}),
    ...(prepared.contractSnapshot ? { contractSnapshot: prepared.contractSnapshot } : {}),
    ...(prepared.depositValue !== undefined ? { depositValue: prepared.depositValue } : {}),
    ...(prepared.depositReferences ? { depositReferences: prepared.depositReferences } : {}),
    ...(requestKey ? { requestKey, requestFingerprint: fingerprint } : {}),
    issuedAt: at,
    issuedBy: input.actor,
    revision: 1,
    updatedAt: at,
    updatedBy: input.actor,
    note: input.note?.trim() || null,
    cancelledAt: null,
    cancelledBy: null,
    cancellationReason: null,
  };
  db.taxInvoices!.push(record);
  syncAllocations(db, id, perBilling, input.actor);
  syncBillingStatus(db, perBilling.keys(), ledgerInvoiceId || null, input.actor);
  syncDeposit(db, record, totals.depositUsd, input.actor);
  if (input.updateCustomerMaster !== false) upsertCustomerMaster(db, client.id, customer, input.actor);
  recordRevision(db, record, "ISSUE", null, input.actor, null);
  log(db, input.actor, "tax_invoice.issue", "tax_invoice", id, `${invoiceNumber} ${totals.totalUsd}`);
  return record;
}

export function editInvoice(db: Database, invoiceId: string, input: InvoiceInput): TaxInvoiceRecord {
  ensureCollections(db);
  const record = db.taxInvoices!.find((entry) => entry.id === invoiceId);
  if (!record) throw new RuleError("NOT_FOUND", "Tax invoice was not found.", 404);
  if (record.status !== "ISSUED") throw new RuleError("INVOICE_CANCELLED", "A cancelled invoice cannot be edited.");
  assertDepositEditable(db, record);
  if (input.invoiceNumber !== undefined && input.invoiceNumber !== record.invoiceNumber) {
    throw new RuleError("NUMBER_IMMUTABLE", "An invoice number never changes.", 400);
  }
  // Changing the customer is an explicit edit: the new customer must be active,
  // its billing lines must be the new customer's (checked with the lines), and a
  // TEST invoice number never moves to a real customer (or back).
  const customerChanged = input.customerId !== record.clientId;
  if (customerChanged) {
    const next = db.clients.find((entry) => entry.id === input.customerId);
    if (!next) throw new RuleError("NOT_FOUND", "Choose a customer.", 404);
    if (!next.active) throw new RuleError("CUSTOMER_INACTIVE", `${next.name} is inactive.`, 409);
    if (isTestCustomer(next.name) !== record.invoiceNumber.startsWith(TEST_NUMBER_PREFIX)) {
      throw new RuleError("SERIES_MISMATCH", "A TEST invoice stays with a TEST customer, and a real one with a real customer.", 409);
    }
  }
  if (!isIsoDate(input.invoiceDate)) throw new RuleError("INVALID", "Enter a valid invoice date.", 400);
  const customer = customerSnapshot(input.customer);
  if (!customer.companyNameEn && !customer.companyNameKm) throw new RuleError("INVALID", "Enter the customer's legal name.", 400);

  const previous = JSON.parse(JSON.stringify(record)) as TaxInvoiceRecord;
  // The rate belongs to the invoice date: kept as saved unless the date changes.
  const rate = input.invoiceDate === record.invoiceDate
    ? { rate: record.exchangeRate, source: record.exchangeRateSource, effectiveDate: record.exchangeRateEffectiveDate, basis: record.exchangeRateBasis, forDate: record.exchangeRateForDate }
    : resolveRate(db, input.invoiceDate, input.exchangeRate);
  const prepared = prepareInvoice(db, input, rate.rate, record.id, record);
  const { lines, perBilling, projectIds } = prepared;
  const totals = prepared.totals;
  if (input.depositUsd && toCents(input.depositUsd) > toCents(totals.totalUsd)) {
    throw new RuleError("INVALID", "The deposit is more than the invoice total.", 400);
  }
  const others = (db.invoicePayments ?? []).filter((p) => p.invoiceId === record.id && p.kind === "PAYMENT" && !p.voidedAt);
  const paidCents = others.reduce((sum, p) => sum + toCents(p.amount), 0) + toCents(totals.depositUsd);
  if (paidCents > toCents(totals.totalUsd)) {
    throw new RuleError("OVERPAID", "Payments already received are more than the new total. Void a payment first.", 409);
  }

  const released = new Set((db.billingAllocations ?? []).filter((a) => a.invoiceId === record.id && !a.voidedAt).map((a) => a.billingItemId));
  const projects = projectIds.map((pid) => db.projects.find((entry) => entry.id === pid)!);
  Object.assign(record, {
    clientId: input.customerId,
    projectId: projectIds[0] ?? record.projectId,
    projectIds,
    invoiceDate: input.invoiceDate,
    customer,
    project: projectIds.length ? { name: projects.map((p) => p.name).join(" · "), note: projects.map((p) => p.note ?? "").filter(Boolean).join("\n") } : record.project,
    lines,
    vatApplicable: input.vatApplicable !== false,
    vatPercent: totals.vatPercent,
    subtotalUsd: totals.subtotalUsd,
    discount: totals.discountUsd > 0 ? input.discount ?? null : null,
    discountUsd: totals.discountUsd,
    discountPolicy: totals.discountPolicy,
    taxableUsd: totals.taxableUsd,
    vatUsd: totals.vatUsd,
    totalUsd: totals.totalUsd,
    exchangeRate: rate.rate,
    exchangeRateSource: rate.source,
    exchangeRateEffectiveDate: rate.effectiveDate,
    exchangeRateBasis: rate.basis,
    exchangeRateForDate: rate.forDate,
    totalKhr: totals.totalKhr,
    depositUsd: totals.depositUsd,
    invoiceKind: prepared.invoiceKind,
    contractId: prepared.contractId,
    contractSnapshot: prepared.contractSnapshot,
    depositValue: prepared.depositValue,
    depositReferences: prepared.depositReferences,
    revision: (record.revision ?? 1) + 1,
    updatedAt: now(),
    updatedBy: input.actor,
    note: input.note === undefined ? record.note ?? null : input.note?.trim() || null,
  } satisfies Partial<TaxInvoiceRecord>);
  syncAllocations(db, record.id, perBilling, input.actor);
  for (const id of perBilling.keys()) released.add(id);
  syncBillingStatus(db, released, record.ledgerInvoiceId || null, input.actor);
  const ledger = db.invoices.find((entry) => entry.id === record.ledgerInvoiceId);
  if (ledger) {
    ledger.invoiceDate = record.invoiceDate;
    ledger.clientId = record.clientId;
    ledger.amount = money([...perBilling.values()].reduce((sum, value) => sum + value, 0));
    ledger.updatedAt = now();
    ledger.updatedBy = input.actor;
  }
  syncDeposit(db, record, totals.depositUsd, input.actor);
  if (input.updateCustomerMaster) upsertCustomerMaster(db, record.clientId, customer, input.actor);
  recordRevision(db, record, "EDIT", previous, input.actor, input.reason?.trim() || null);
  log(db, input.actor, "tax_invoice.edit", "tax_invoice", record.id, `${record.invoiceNumber} rev ${record.revision}`);
  return record;
}

export function cancelInvoice(db: Database, invoiceId: string, reason: string, actor: string): TaxInvoiceRecord {
  ensureCollections(db);
  const record = db.taxInvoices!.find((entry) => entry.id === invoiceId);
  if (!record) throw new RuleError("NOT_FOUND", "Tax invoice was not found.", 404);
  if (record.status !== "ISSUED") throw new RuleError("ALREADY_CANCELLED", "This tax invoice was already cancelled.");
  assertDepositEditable(db, record);
  const trimmed = reason.trim();
  if (!trimmed) throw new RuleError("INVALID", "Enter a reason for cancelling.", 400);
  if ((db.invoicePayments ?? []).some((p) => p.invoiceId === invoiceId && !p.voidedAt)) {
    throw new RuleError("INVOICE_PAID", "This invoice has payments. Void them (or set the deposit to 0) before cancelling.");
  }
  const ledger = db.invoices.find((entry) => entry.id === record.ledgerInvoiceId);
  if (ledger?.status === "PAID") throw new RuleError("INVOICE_PAID", "This invoice is paid. Undo the payment before cancelling it.");
  const previous = JSON.parse(JSON.stringify(record)) as TaxInvoiceRecord;
  const released = new Set((db.billingAllocations ?? []).filter((a) => a.invoiceId === record.id && !a.voidedAt).map((a) => a.billingItemId));
  syncAllocations(db, record.id, new Map(), actor);
  if (ledger && ledger.status !== "VOID") {
    ledger.status = "VOID";
    ledger.receiptStatus = "NOT_REQUIRED";
    ledger.updatedAt = now();
    ledger.updatedBy = actor;
  }
  syncBillingStatus(db, released, record.ledgerInvoiceId || null, actor);
  for (const id of released) {
    const item = db.billingItems.find((entry) => entry.id === id);
    if (item && item.invoiceId === record.ledgerInvoiceId) item.invoiceId = null;
  }
  db.invoiceItems = db.invoiceItems.filter((link) => link.invoiceId !== record.ledgerInvoiceId);
  record.status = "CANCELLED";
  record.cancelledAt = now();
  record.cancelledBy = actor;
  record.cancellationReason = trimmed;
  record.revision = (record.revision ?? 1) + 1;
  record.updatedAt = record.cancelledAt;
  record.updatedBy = actor;
  recordRevision(db, record, "CANCEL", previous, actor, trimmed);
  log(db, actor, "tax_invoice.cancel", "tax_invoice", record.id, `${record.invoiceNumber}: ${trimmed}`);
  return record;
}

